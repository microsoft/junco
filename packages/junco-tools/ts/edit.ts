import { homedir } from "node:os";
import type { AgentTool, AgentToolResult } from "@earendil-works/pi-agent-core";
import type { ToolDefinition } from "@earendil-works/pi-coding-agent";
import { Type } from "typebox";
import type { EditFileOutcome, EditStore, NativeMux } from "../native/index.js";
import type { NativeModule } from "./native.js";
import {
  captureRecorder,
  markProfileOwned,
  type ProfileRecorder,
  profileToolCall,
} from "./profile-recorder.js";
import { throwIfAborted } from "./tool-support.js";

const EDIT_APPLY = {
  resource: "edits",
  category: "edit",
  tool: "edit",
  operation: "apply",
} as const;

/** Per-file outcome counts of one applied patch; text sizes are file sizes, not deltas. */
function editMetrics({ details }: AgentToolResult<HashlineEditDetails>) {
  const counters: Record<string, number> = {
    files_created: 0,
    files_updated: 0,
    files_deleted: 0,
    files_moved: 0,
    warnings: 0,
    parse_regressions: 0,
    snapshots_pruned: 0,
  };
  for (const file of details.files) {
    if (file.op === "create") counters.files_created++;
    else if (file.op === "update") counters.files_updated++;
    else if (file.op === "delete") counters.files_deleted++;
    if (file.moveTo !== undefined) counters.files_moved++;
    counters.warnings += file.warnings.length;
    counters.parse_regressions += Number(file.parseRegressed);
    counters.snapshots_pruned += Number(file.snapshotsPruned);
    if (file.oldText !== undefined)
      counters.old_text_bytes =
        (counters.old_text_bytes ?? 0) + Buffer.byteLength(file.oldText);
    if (file.newText !== undefined)
      counters.new_text_bytes =
        (counters.new_text_bytes ?? 0) + Buffer.byteLength(file.newText);
  }
  return { counters };
}

const editSchema = Type.Object({
  input: Type.String({
    description:
      "Hashline patch: [path#TAG] sections followed by PUT/CUT/REM/MV operations.",
  }),
});

/**
 * Per-file results of a hashline apply.
 *
 * Deliberately not Pi's `EditToolDetails`: this tool runs the pi-edit engine,
 * whose outcomes carry hashline diffs, warnings, and move destinations.
 */
export interface HashlineEditDetails {
  files: EditFileOutcome[];
}

/**
 * The upstream hashline edit engine, applied as one routed marsh call.
 *
 * Each call stages its patch natively over the collection's shared
 * `EditStore`, so snapshots recorded by `read`/`grep`, named clipboard
 * registers, and stale-anchor recovery all survive across calls. `mux` writes
 * every file through the call's marsh context: its policy may run the edit in
 * a private snapshot whose changes publish only when marsh authorizes them,
 * and a refused publication rejects the call. Compute and parse failures stage
 * nothing; a writer error between writes can leave earlier files already
 * written, exactly as the engine does natively.
 */
export const EditTool = {
  create(
    cwd: string,
    store: EditStore,
    native: NativeModule,
    mux: NativeMux,
    recorder?:
      | ProfileRecorder<"edits">
      | (() => ProfileRecorder<"edits"> | undefined),
  ): AgentTool<typeof editSchema, HashlineEditDetails> {
    const tool = {
      name: "edit",
      label: "Edit",
      description: native.editDescription("hashline"),
      promptSnippet: "Edit files with snapshot-anchored hashline patches",
      promptGuidelines: [
        "Obtain [path#TAG] and numbered lines from read or grep before editing.",
      ],
      parameters: editSchema,
      executionMode: "sequential",
      execute(_toolCallId, params, signal) {
        return profileToolCall(
          captureRecorder(recorder),
          EDIT_APPLY,
          signal,
          async () => {
            throwIfAborted(signal);
            // Pass the complete arguments through the engine's no-delta path.
            const outcome = await mux.edit(
              cwd,
              store,
              {
                cwd,
                homeDir: homedir(),
                mode: "hashline",
                allowFuzzy: true,
                fuzzyThreshold: 0.95,
                enforceSeenLines: true,
                blockAutoGenerated: true,
                urlSchemes: [],
                urlAliasSchemes: [],
                planActive: false,
                planWritableRoots: [],
                rawInput: false,
              },
              JSON.stringify(params),
            );
            throwIfAborted(signal);
            if (outcome.isError) throw new Error(outcome.text);
            return {
              content: [{ type: "text", text: outcome.text }],
              details: { files: outcome.files },
            };
          },
          editMetrics,
        );
      },
    } satisfies ToolDefinition<typeof editSchema, HashlineEditDetails>;
    return markProfileOwned(tool, () => EDIT_APPLY);
  },
};
