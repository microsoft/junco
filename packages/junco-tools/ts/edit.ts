import { homedir } from "node:os";
import type { AgentTool } from "@earendil-works/pi-agent-core";
import type { ToolDefinition } from "@earendil-works/pi-coding-agent";
import { Type } from "typebox";
import type { EditFileOutcome, EditStore, NativeMux } from "../native/index.js";
import type { NativeModule } from "./native.js";
import { throwIfAborted } from "./tool-support.js";

const editSchema = Type.Object({
  input: Type.String({
    description: "Hashline patch: [path#TAG] sections followed by PUT/CUT/REM/MV operations.",
  }),
});

/**
 * Per-file results of a hashline apply.
 *
 * Deliberately not Pi's `EditToolDetails`: this tool runs the pi-edit engine,
 * whose outcomes carry hashline diffs, warnings, and move destinations.
 */
export interface HashlineEditDetails {
  files: EditFileOutcome[];
}

/**
 * The upstream hashline edit engine, applied as one routed marsh call.
 *
 * Each call stages its patch natively over the collection's shared
 * `EditStore`, so snapshots recorded by `read`/`grep`, named clipboard
 * registers, and stale-anchor recovery all survive across calls. `mux` writes
 * every file through the call's marsh context: its policy may run the edit in
 * a private snapshot whose changes publish only when marsh authorizes them,
 * and a refused publication rejects the call. Compute and parse failures stage
 * nothing; a writer error between writes can leave earlier files already
 * written, exactly as the engine does natively.
 */
export function createEditTool(
  cwd: string,
  store: EditStore,
  native: NativeModule,
  mux: NativeMux,
): AgentTool<typeof editSchema, HashlineEditDetails> {
  const tool = {
    name: "edit",
    label: "Edit",
    description: native.editDescription("hashline"),
    promptSnippet: "Edit files with snapshot-anchored hashline patches",
    promptGuidelines: ["Obtain [path#TAG] and numbered lines from read or grep before editing."],
    parameters: editSchema,
    executionMode: "sequential",
    async execute(_toolCallId, params, signal) {
      throwIfAborted(signal);
      // Pass the complete arguments through the engine's no-delta path.
      const outcome = await mux.edit(
        cwd,
        store,
        {
          cwd,
          homeDir: homedir(),
          mode: "hashline",
          allowFuzzy: true,
          fuzzyThreshold: 0.95,
          enforceSeenLines: true,
          blockAutoGenerated: true,
          planActive: false,
          rawInput: false,
        },
        JSON.stringify(params),
      );
      throwIfAborted(signal);
      if (outcome.isError) throw new Error(outcome.text);
      return {
        content: [{ type: "text", text: outcome.text }],
        details: { files: outcome.files },
      };
    },
  } satisfies ToolDefinition<typeof editSchema, HashlineEditDetails>;
  return tool;
}
