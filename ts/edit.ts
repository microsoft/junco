import { mkdir, unlink, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname } from "node:path";
import type { ToolDefinition } from "@earendil-works/pi-coding-agent";
import { Type } from "typebox";
import type { EditFileOutcome, EditStore, EditWriteRequest, EditWriteResponse } from "../native/index.js";
import type { NativeModule } from "./native.js";
import { throwIfAborted } from "./tool-support.js";

const editSchema = Type.Object({
  input: Type.String({
    description: "Hashline patch: [path#TAG] sections followed by PUT/CUT/REM/MV operations.",
  }),
});

/**
 * Per-file results of a hashline apply.
 *
 * Deliberately not Pi's `EditToolDetails`: this tool runs the pi-edit engine,
 * whose outcomes carry hashline diffs, warnings, and move destinations.
 */
export interface HashlineEditDetails {
  files: EditFileOutcome[];
}

/**
 * The upstream hashline edit engine, wired to real filesystem writes.
 *
 * Each call opens one `EditSession` over the collection's shared `EditStore`,
 * so snapshots recorded by `read`/`grep`, named clipboard registers, and
 * stale-anchor recovery all survive across calls. Compute and parse failures
 * stage nothing; a writer error or cancellation between writes can leave
 * earlier files already written, exactly as the engine does natively.
 */
export function createHashlineEditToolDefinition(
  cwd: string,
  store: EditStore,
  native: NativeModule,
): ToolDefinition<typeof editSchema, HashlineEditDetails> {
  return {
    name: "edit",
    label: "Edit",
    description: native.editDescription("hashline"),
    promptSnippet: "Edit files with snapshot-anchored hashline patches",
    promptGuidelines: ["Obtain [path#TAG] and numbered lines from read or grep before editing."],
    parameters: editSchema,
    executionMode: "sequential",
    async execute(_toolCallId, params, signal) {
      throwIfAborted(signal);
      // Paths whose bytes or names this call attempted to change. Recorded
      // before the operation runs so a half-finished write or move can never
      // leave a stale scan-cache entry looking fresh.
      const touched = new Set<string>();
      const writer = async (
        error: Error | null,
        request: EditWriteRequest,
      ): Promise<EditWriteResponse> => {
        if (error) throw error;
        throwIfAborted(signal);
        const { op, path, moveTo, content } = request;
        if (op === "delete") {
          touched.add(path);
          await unlink(path);
          return { written: "" };
        }
        if (op === "move") {
          if (moveTo === undefined || moveTo === null) {
            throw new Error("Native edit move request omitted destination");
          }
          if (content === undefined || content === null) {
            throw new Error("Native edit move request omitted content");
          }
          touched.add(path);
          touched.add(moveTo);
          await mkdir(dirname(moveTo), { recursive: true });
          await writeFile(moveTo, content, "utf-8");
          await unlink(path);
          return { written: content };
        }
        if (op === "create" || op === "update") {
          if (content === undefined || content === null) {
            throw new Error(`Native edit ${op} request omitted content`);
          }
          touched.add(path);
          if (op === "create") await mkdir(dirname(path), { recursive: true });
          await writeFile(path, content, "utf-8");
          return { written: content };
        }
        throw new Error(`Unknown native edit operation: ${op}`);
      };

      const session = new native.EditSession(store, {
        cwd,
        homeDir: homedir(),
        mode: "hashline",
        allowFuzzy: true,
        fuzzyThreshold: 0.95,
        enforceSeenLines: true,
        blockAutoGenerated: true,
        planActive: false,
        rawInput: false,
      });
      let outcome;
      try {
        // Pi 0.80.6 has no streamed-argument interface, so the complete
        // arguments go in through the engine's no-delta path.
        session.setArgsJson(JSON.stringify(params));
        session.finish();
        throwIfAborted(signal);
        outcome = await session.apply({ lspFlush: false }, writer);
      } finally {
        for (const path of touched) native.invalidateFsScanCache(path);
        session.close();
      }
      throwIfAborted(signal);
      if (outcome.isError) throw new Error(outcome.text);
      return {
        content: [{ type: "text", text: outcome.text }],
        details: { files: outcome.files },
      };
    },
  };
}
